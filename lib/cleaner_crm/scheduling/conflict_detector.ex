defmodule CleanerCrm.Scheduling.ConflictDetector do
  @moduledoc """
  Detects scheduling conflicts against a cleaner's availability blocks
  and already-booked jobs — for a single proposed assignment, or across
  every occurrence in a recurring series (unsaved, or already
  materialized).

  Two distinct reasons, surfaced separately so the UI can say something
  useful:

    * `:unavailable` — the cleaner has a time-off block covering the slot
    * `:overlap` — the cleaner already has another job booked then

  Availability is checked first: a time-off block is the more specific
  reason when both happen to apply.
  """

  import Ecto.Query, warn: false

  alias CleanerCrm.Repo
  alias CleanerCrm.Scheduling.{AvailabilityBlock, Job, RecurringPlan}
  alias CleanerCrm.Users.Scope

  @doc """
  Checks one proposed (cleaner, date, time window) assignment.

  `opts`:

    * `:exclude_job_id` — omit a job (the one being reassigned) from
      the overlap check against itself
    * `:exclude_recurring_plan_id` — omit every job generated by this
      plan — its own sibling occurrences are not a conflict with each
      other

  Returns `:ok` when the cleaner is `nil` — an unassigned job never
  conflicts.
  """
  def check_assignment(scope, cleaner_id, date, start_time, end_time, opts \\ [])

  def check_assignment(
        %Scope{active_account_id: account_id},
        cleaner_id,
        %Date{} = date,
        start_time,
        end_time,
        opts
      )
      when not is_nil(account_id) and not is_nil(cleaner_id) do
    cond do
      unavailable?(account_id, cleaner_id, date, start_time, end_time) ->
        {:error, :unavailable}

      overlaps_existing_job?(account_id, cleaner_id, date, start_time, end_time, opts) ->
        {:error, :overlap}

      true ->
        :ok
    end
  end

  def check_assignment(_scope, nil, _date, _start_time, _end_time, _opts), do: :ok

  @doc """
  Checks every occurrence of a plan's series (`[%{index:, date:}, ...]`,
  as returned by `CleanerCrm.Scheduling.Recurrence.occurrences/1`)
  against that plan's preferred cleaner. Works the same whether the
  plan is unsaved (a live preview) or already saved with its jobs
  materialized — in the latter case, the plan's own jobs are excluded
  from the overlap check against themselves. Returns only the
  conflicting occurrences, as `[%{index:, date:, reason:}]`.
  """
  def check_occurrences(_scope, %RecurringPlan{cleaner_id: nil}, _occurrences), do: []

  def check_occurrences(scope, %RecurringPlan{} = plan, occurrences) do
    opts = [exclude_recurring_plan_id: plan.id]

    occurrences
    |> Enum.map(fn %{index: index, date: date} ->
      case check_assignment(scope, plan.cleaner_id, date, plan.start_time, plan.end_time, opts) do
        :ok -> nil
        {:error, reason} -> %{index: index, date: date, reason: reason}
      end
    end)
    |> Enum.reject(&is_nil/1)
  end

  defp unavailable?(account_id, cleaner_id, date, start_time, end_time) do
    AvailabilityBlock
    |> where(
      [b],
      b.account_id == ^account_id and b.cleaner_id == ^cleaner_id and b.date == ^date
    )
    |> Repo.all()
    |> Enum.any?(&blocks?(&1, start_time, end_time))
  end

  defp blocks?(%AvailabilityBlock{all_day: true}, _start_time, _end_time), do: true

  defp blocks?(
         %AvailabilityBlock{start_time: block_start, end_time: block_end},
         start_time,
         end_time
       ) do
    overlaps?(block_start, block_end, start_time, end_time)
  end

  defp overlaps_existing_job?(account_id, cleaner_id, date, start_time, end_time, opts) do
    Job
    |> where(
      [j],
      j.account_id == ^account_id and j.cleaner_id == ^cleaner_id and
        j.scheduled_date == ^date and j.status != :cancelled
    )
    |> exclude_job(opts[:exclude_job_id])
    |> exclude_plan(opts[:exclude_recurring_plan_id])
    |> Repo.all()
    |> Enum.any?(&overlaps?(&1.start_time, &1.end_time, start_time, end_time))
  end

  defp exclude_job(query, nil), do: query
  defp exclude_job(query, job_id), do: where(query, [j], j.id != ^job_id)

  defp exclude_plan(query, nil), do: query

  defp exclude_plan(query, plan_id) do
    where(query, [j], is_nil(j.recurring_plan_id) or j.recurring_plan_id != ^plan_id)
  end

  defp overlaps?(start_a, end_a, start_b, end_b) do
    Time.compare(start_a, end_b) == :lt and Time.compare(start_b, end_a) == :lt
  end
end
